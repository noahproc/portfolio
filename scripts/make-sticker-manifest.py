"""Regenerate assets/js/stickers.js: every sticker in assets/images/stickers and its aspect ratio,
for the sticker packer in assets/js/site.js. Run after adding or removing a sticker:
python3 scripts/make-sticker-manifest.py
Only Noah's own stickers belong in that folder (cut from the sheets he supplied)."""
import json, os
from PIL import Image

DIR = 'assets/images/stickers'
items = []
for f in sorted(os.listdir(DIR)):
    if f.endswith('.webp'):
        w, h = Image.open(os.path.join(DIR, f)).size
        items.append({'n': f[:-5], 'r': round(w / h, 3)})
with open('assets/js/stickers.js', 'w') as out:
    out.write('/* Generated by scripts/make-sticker-manifest.py: every sticker and its aspect ratio (w/h), for the packer in site.js. */\n')
    out.write('window.STICKERS=' + json.dumps(items, separators=(',', ':')) + ';\n')
print(len(items), 'stickers')
